#!/bin/bash

# Проверяем, передан ли аргумент
if [ -z "$1" ]; then
    echo "Использование: $0 <имя_файла>"
    exit 1
fi

# Проверяем, существует ли файл
if [ ! -f "$1" ]; then
    echo "Ошибка: Файл '$1' не найден."
    exit 1
fi

# Добавляем нулевой байт (\0) в конец файла
printf '\0' >> "$1"

echo "Нулевой байт успешно добавлен в конец файла: $1"